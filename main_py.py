import pygame
import random
import sys


pygame.init()

# Dimensiones de la ventana y configuración general
ANCHO, ALTO = 900, 650
VENTANA = pygame.display.set_mode((ANCHO, ALTO))
pygame.display.set_caption("Visualizador Avanzado de Algoritmo de Ordenamiento - Bubble Sort (Pygame)")


COLOR_FONDO = (18, 18, 24)       # Gris oscuro moderno
COLOR_BARRA = (70, 130, 185)     # Azul principal
COLOR_COMPARANDO = (235, 87, 87) # Rojo vibrante para elementos activos
COLOR_ORDENADO = (46, 204, 113)  # Verde esmeralda para elementos finalizados
COLOR_TEXTO = (240, 240, 240)    # Blanco suave para la interfaz


FUENTE = pygame.font.SysFont("Arial", 22)
FUENTE_TITULO = pygame.font.SysFont("Arial", 26, bold=True)

# Parámetros del conjunto de datos
CANTIDAD_BARRAS = 60
ANCHO_BARRA = ANCHO // CANTIDAD_BARRAS

def generar_datos():
    """Genera una lista de valores aleatorios para las barras de la simulación."""
    return [random.randint(40, ALTO - 100) for _ in range(CANTIDAD_BARRAS)]

def dibujar_interfaz(ventana, datos, indice_j=-1, ordenado=False):
    """Dibuja todos los elementos visuales, barras de estado y textos explicativos."""
    ventana.fill(COLOR_FONDO)

    # Renderizar título superior
    titulo = FUENTE_TITULO.render("Simulación de Bubble Sort en Python (Pygame)", True, COLOR_TEXTO)
    ventana.blit(titulo, (ANCHO // 2 - titulo.get_width() // 2, 20))

    # Instrucciones de control
    instruccion = FUENTE.render("Presiona [R] para reiniciar | [ESC] para salir", True, (160, 160, 175))
    ventana.blit(instruccion, (ANCHO // 2 - instruccion.get_width() // 2, 55))

    # Dibujar las barras del algoritmo
    for i, val in enumerate(datos):
        x = i * ANCHO_BARRA
        y = ALTO - val - 40

        # Asignación de colores según el estado del elemento
        color = COLOR_BARRA
        if ordenado:
            color = COLOR_ORDENADO
        elif i == indice_j or i == indice_j + 1:
            color = COLOR_COMPARANDO

        # Dibujar rectángulo de la barra
        pygame.draw.rect(ventana, color, (x + 2, y, ANCHO_BARRA - 4, val), border_radius=3)

    pygame.display.flip()

def main():
    reloj = pygame.time.Clock()
    datos = generar_datos()

    n = len(datos)
    i = 0
    j = 0
    en_proceso = True
    ordenado = False

    # Bucle principal del programa
    while True:
        reloj.tick(45) # Control de velocidad de los fotogramas por segundo (FPS)

        # Gestión de eventos de teclado y ventana
        for evento in pygame.event.get():
            if evento.type == pygame.QUIT:
                pygame.quit()
                sys.exit()
            elif evento.type == pygame.KEYDOWN:
                if evento.key == pygame.K_ESCAPE:
                    pygame.quit()
                    sys.exit()
                elif evento.key == pygame.K_r: # Reiniciar simulación
                    datos = generar_datos()
                    i = 0
                    j = 0
                    en_proceso = True
                    ordenado = False

        # Lógica del Bubble Sort integrada en el flujo de Pygame
        if en_proceso:
            if i < n:
                if j < n - i - 1:
                    if datos[j] > datos[j + 1]:
                        datos[j], datos[j + 1] = datos[j + 1], datos[j]
                    j += 1
                else:
                    j = 0
                    i += 1
            else:
                en_proceso = False
                ordenado = True

        dibujar_interfaz(VENTANA, datos, j, ordenado)

if __name__ == "__main__":
    main()